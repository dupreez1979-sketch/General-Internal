// Bridges the folder page to the desktop app. Only these functions are exposed.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

// Only the app's own folder page gets these: never a web page, even if one were somehow loaded here.
if (location.protocol === 'file:') contextBridge.exposeInMainWorld('navigatorApp', {
  isElectron: true,
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  openMail: (url) => ipcRenderer.invoke('open-mail', url),
  claraMail: (opts) => ipcRenderer.invoke('clara-mail', opts),
  openWindow: (url) => ipcRenderer.invoke('open-window', url),
  showInFolder: (file) => ipcRenderer.invoke('show-in-folder', file),
  openFile: (file) => ipcRenderer.invoke('open-file', file),
  onShortcut: (fn) => ipcRenderer.on('shortcut', (_e, action) => fn(action)),
  onDownload: (fn) => ipcRenderer.on('download', (_e, info) => fn(info)),
  refreshLibrary: (opts) => ipcRenderer.invoke('library-refresh', opts),
  deleteChats: (items) => ipcRenderer.invoke('claude-delete-chats', items),
  renameChat: (item) => ipcRenderer.invoke('claude-rename-chat', item),
  designLook: (url) => ipcRenderer.invoke('design-look', url),
  claudePageDetails: (url) => ipcRenderer.invoke('claude-page-details', url),
  projectScheduled: (url) => ipcRenderer.invoke('project-scheduled', url),
  cosExport: (req) => ipcRenderer.invoke('cos-export', req),
  cosShowExport: () => ipcRenderer.invoke('cos-show-export'),
  backupWrite: (text) => ipcRenderer.invoke('backup-write', text),
  backupList: () => ipcRenderer.invoke('backup-list'),
  backupRead: (name) => ipcRenderer.invoke('backup-read', name),
  backupReveal: () => ipcRenderer.invoke('backup-reveal'),
  updateStatus: () => ipcRenderer.invoke('update-status'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateReady: (fn) => ipcRenderer.on('update-ready', (_e, info) => fn(info)),
  liveInfo: () => ipcRenderer.invoke('live-info'),
  mondayStatus: () => ipcRenderer.invoke('monday-status'),
  mondayConnect: (token) => ipcRenderer.invoke('monday-connect', token),
  mondayDisconnect: () => ipcRenderer.invoke('monday-disconnect'),
  mondayFetch: () => ipcRenderer.invoke('monday-fetch'),
  mondayCreateBoard: (opts) => ipcRenderer.invoke('monday-create-board', opts),
  mondayRenameBoard: (id, name) => ipcRenderer.invoke('monday-rename-board', id, name),
  mondayDeleteBoards: (ids) => ipcRenderer.invoke('monday-delete-boards', ids),
  onLiveStatus: (fn) => ipcRenderer.on('live-status', (_e, info) => fn(info)),
  harvestPane: (webContentsId, kind) => ipcRenderer.invoke('harvest-pane', webContentsId, kind),
  onChildNavigated: (fn) => ipcRenderer.on('child-navigated', (_e, info) => fn(info)),
  // Folders on this computer
  fsStatus: () => ipcRenderer.invoke('fs-status'),
  fsEnable: (root) => ipcRenderer.invoke('fs-enable', root),
  fsDisable: () => ipcRenderer.invoke('fs-disable'),
  fsChooseRoot: () => ipcRenderer.invoke('fs-choose-root'),
  fsScan: () => ipcRenderer.invoke('fs-scan'),
  fsApply: (payload) => ipcRenderer.invoke('fs-apply', payload),
  fsOpen: (rel) => ipcRenderer.invoke('fs-open', rel),
  fsReveal: (rel) => ipcRenderer.invoke('fs-reveal', rel),
  fsAbs: (rel) => ipcRenderer.invoke('fs-abs', rel),
  fsCosNotes: (profileRel, files) => ipcRenderer.invoke('fs-cos-notes', profileRel, files),
  fsNewFile: (kind, destRel, name) => ipcRenderer.invoke('fs-new-file', kind, destRel, name),
  fsImport: (paths, destRel) => ipcRenderer.invoke('fs-import', paths, destRel),
  fsCopy: (srcRel, destDirRel, keepName) => ipcRenderer.invoke('fs-copy', srcRel, destDirRel, keepName),
  onFsChanged: (fn) => ipcRenderer.on('fs-changed', () => fn()),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch (e) { return ''; } },
  onContextAction: (fn) => ipcRenderer.on('context-action', (_e, info) => fn(info)),
});
